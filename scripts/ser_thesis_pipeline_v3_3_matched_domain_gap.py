    def run_within_corpus_e3(self):
        """
        Train a fresh frozen-E3 model independently on each selected corpus and
        evaluate ONLY on that corpus's held-out internal test set.

        This is not an ablation campaign and performs no model selection across
        corpora. Validation is used only for checkpointing/early stopping inside
        each corpus.
        """
        campaign_name = "within_corpus_E3_internal"
        campaign_dir = self.campaign_root / campaign_name
        campaign_dir.mkdir(parents=True, exist_ok=True)

        config = self.frozen_e3_config()
        datasets = [str(x).lower() for x in self.args.within_datasets]

        unknown = sorted(set(datasets) - set(ALL_DATASETS))
        if unknown:
            raise ValueError(
                f"Unknown --within-datasets values: {unknown}; "
                f"allowed={ALL_DATASETS}"
            )

        atomic_write_json(
            campaign_dir / "frozen_E3_config.json",
            {
                "pipeline_version": PIPELINE_VERSION,
                "campaign": campaign_name,
                "datasets": datasets,
                "seeds": self.args.seeds,
                "scientific_design": (
                    "fresh E3 training per corpus; held-out same-corpus internal test only"
                ),
                "frozen_e3": config,
                "created_at_utc": utc_now(),
            },
        )

        ledger = self.load_ledger(campaign_name)
        split_audit_rows = []
        completion_rows = []

        for dataset_name in datasets:
            split, protocol, split_hash = self.get_or_create_within_corpus_split(
                dataset_name
            )

            train_df = (
                split.loc[split["split"] == "train"]
                .copy()
                .reset_index(drop=True)
            )
            val_df = (
                split.loc[split["split"] == "validation"]
                .copy()
                .reset_index(drop=True)
            )
            test_df = (
                split.loc[split["split"] == "test"]
                .copy()
                .reset_index(drop=True)
            )

            norm = self.get_within_corpus_normalization(
                dataset_name=dataset_name,
                train_frame=train_df,
                split_sha256=split_hash,
                arf_mode=config["arf_mode"],
            )

            for split_name, part in [
                ("train", train_df),
                ("validation", val_df),
                ("test", test_df),
            ]:
                counts = (
                    part["label_id"]
                    .astype(int)
                    .value_counts()
                    .reindex(range(1, NUM_CLASSES + 1), fill_value=0)
                )
                row = {
                    "dataset": dataset_name,
                    "split": split_name,
                    "n_samples": int(len(part)),
                    "fraction": float(len(part) / len(split)),
                    "split_strategy": protocol["strategy"],
                    "group_source": protocol.get("group_source"),
                    "split_sha256": split_hash,
                }
                for label_id in range(1, NUM_CLASSES + 1):
                    row[
                        f"n_{LABEL_ID_TO_EMOTION[label_id].lower()}"
                    ] = int(counts.loc[label_id])
                split_audit_rows.append(row)

            logical_experiment_id = (
                f"E3_{dataset_name.upper()}_INTERNAL"
            )

            if not self.args.skip_preflight:
                print(
                    f"\nPreflight {campaign_name}/{logical_experiment_id}"
                )
                self.preflight(
                    config=config,
                    seed=self.args.seeds[0],
                    dataframe=train_df,
                    normalization_override=norm,
                )

            for seed in self.args.seeds:
                model, paths, completion = self.train_one(
                    campaign_name=campaign_name,
                    logical_experiment_id=logical_experiment_id,
                    config=config,
                    seed=seed,
                    train_dataframe=train_df,
                    val_dataframe=val_df,
                    normalization_override=norm,
                    split_sha256=split_hash,
                    training_dataset=dataset_name,
                )

                completion_rows.append(
                    {
                        "dataset": dataset_name,
                        "experiment": logical_experiment_id,
                        "seed": int(seed),
                        "split_strategy": protocol["strategy"],
                        "best_val_uar": completion["best_val_uar"],
                        "best_epoch": completion["best_epoch"],
                        "completed_epochs": completion["completed_epochs"],
                    }
                )

                eval_name = f"{dataset_name}_internal_test"
                if self.metric_exists(
                    ledger,
                    logical_experiment_id,
                    seed,
                    eval_name,
                ):
                    print(
                        f"✓ {logical_experiment_id}/seed{seed}/{eval_name}: "
                        "already evaluated — skipping."
                    )
                else:
                    print(
                        f"Evaluating {logical_experiment_id}/seed{seed} "
                        f"on held-out {dataset_name.upper()} test..."
                    )
                    metric_row = self.evaluate_one(
                        model=model,
                        dataframe=test_df,
                        config=config,
                        seed=seed,
                        logical_experiment_id=logical_experiment_id,
                        eval_name=eval_name,
                        paths=paths,
                        normalization_override=norm,
                    )
                    metric_row.update(
                        {
                            "training_dataset": dataset_name,
                            "evaluation_dataset": dataset_name,
                            "protocol": "within_corpus_internal",
                            "split_strategy": protocol["strategy"],
                            "group_source": protocol.get("group_source"),
                            "split_sha256": split_hash,
                        }
                    )
                    ledger = self.upsert_metric(
                        campaign_name, ledger, metric_row
                    )
                    print(
                        f"✓ {dataset_name.upper()} seed {seed}: "
                        f"internal UAR={metric_row['uar']:.5f}"
                    )

                del model
                tf.keras.backend.clear_session()
                gc.collect()

        if split_audit_rows:
            atomic_write_csv(
                pd.DataFrame(split_audit_rows).drop_duplicates(),
                self.summary_root / "within_corpus_split_audit.csv",
            )

        if completion_rows:
            completion_df = pd.DataFrame(completion_rows)
            atomic_write_csv(
                completion_df,
                campaign_dir / "validation_summary_by_run.csv",
            )

        self.analyze_within_corpus()

