    def preflight(
        self,
        config: dict,
        seed: int,
        dataframe: Optional[pd.DataFrame] = None,
        normalization_override: Optional[dict] = None,
    ):
        tf.keras.backend.clear_session()
        gc.collect()
        tf.keras.utils.set_random_seed(seed)

        model = self.compile_model(
            self.build_model(config["model"]),
            config,
        )

        seq = self.make_sequence(
            dataframe=self.train_df if dataframe is None else dataframe,
            config=config,
            training=True,
            seed=seed,
            shuffle=False,
            initial_epoch=0,
            normalization_override=normalization_override,
        )

        x, y = seq[0]

        if tuple(x.shape[1:]) != tuple(self.INPUT_SHAPE):
            raise RuntimeError(
                f"Preflight feature mismatch: {x.shape[1:]} vs {self.INPUT_SHAPE}"
            )
        if y.shape[1] != NUM_CLASSES:
            raise RuntimeError(f"Preflight target mismatch: {y.shape}")
        if not np.isfinite(x).all() or not np.isfinite(y).all():
            raise RuntimeError("NaN/Inf detected during preflight.")

        result = model.train_on_batch(x, y, return_dict=True)

        if not np.isfinite(float(result["loss"])):
            raise RuntimeError("Non-finite preflight loss.")

        print(
            f"✓ Preflight: model={config['model']} "
            f"ARF={config['arf_mode']} "
            f"params={model.count_params():,} "
            f"batch={x.shape[0]} loss={float(result['loss']):.5f}"
        )

        del model, seq, x, y
        tf.keras.backend.clear_session()
        gc.collect()

    def train_one(
        self,
        campaign_name: str,
        logical_experiment_id: str,
        config: dict,
        seed: int,
        train_dataframe: Optional[pd.DataFrame] = None,
        val_dataframe: Optional[pd.DataFrame] = None,
        normalization_override: Optional[dict] = None,
        split_sha256: Optional[str] = None,
        training_dataset: Optional[str] = None,
    ):
        run_key = f"{logical_experiment_id}_seed{seed}"
        paths = self.run_paths(campaign_name, run_key)

        effective_train_df = self.train_df if train_dataframe is None else train_dataframe
        effective_val_df = self.val_df if val_dataframe is None else val_dataframe
        effective_split_hash = str(split_sha256 or self.split_hash)

        config_hash, config_payload = self.config_fingerprint(
            logical_experiment_id,
            campaign_name,
            seed,
            config,
            split_sha256=effective_split_hash,
            training_dataset=training_dataset,
        )

        print("\n" + "=" * 96)
        print(
            f"{campaign_name} :: {logical_experiment_id} :: seed={seed}"
        )
        print(config)
        print("=" * 96)

        if paths.config_json.exists():
            with paths.config_json.open("r", encoding="utf-8") as f:
                old = json.load(f)
            if old.get("config_hash") != config_hash:
                raise RuntimeError(
                    f"{run_key}: experiment directory contains a different "
                    "configuration. Refusing unsafe resume/overwrite."
                )
        else:
            payload = dict(config_payload)
            payload["config_hash"] = config_hash
            payload["created_at_utc"] = utc_now()
            atomic_write_json(paths.config_json, payload)

        # Completed run: load inference model without rebuilding optimizer state.
        if paths.completion.exists():
            with paths.completion.open("r", encoding="utf-8") as f:
                done = json.load(f)
            if done.get("config_hash") != config_hash:
                raise RuntimeError(
                    f"{run_key}: completion marker config mismatch."
                )
            print(f"✓ {run_key}: training already complete — loading best weights.")
            model = self.build_model(config["model"])
            model.load_weights(paths.best_weights)
            return model, paths, done

        model, resume_state, history_rows = self._load_resume(
            paths, config_hash
        )

        if model is not None:
            initial_epoch = int(resume_state["completed_epochs"])
            print(
                f"↻ {run_key}: committed resume checkpoint found. "
                f"Continuing after epoch {initial_epoch}."
            )
            model.optimizer.learning_rate.assign(
                float(resume_state["current_lr"])
            )
        else:
            initial_epoch = 0
            history_rows = []
            tf.keras.backend.clear_session()
            gc.collect()
            tf.keras.utils.set_random_seed(seed)
            model = self.compile_model(
                self.build_model(config["model"]),
                config,
            )

        train_seq = self.make_sequence(
            dataframe=effective_train_df,
            config=config,
            training=True,
            seed=seed,
            shuffle=True,
            initial_epoch=initial_epoch,
            normalization_override=normalization_override,
        )

        val_seq = self.make_sequence(
            dataframe=effective_val_df,
            config=config,
            training=False,
            seed=seed,
            shuffle=False,
            initial_epoch=initial_epoch,
            normalization_override=normalization_override,
        )

        control = ResumableTrainingControl(
            pipeline=self,
            logical_experiment_id=logical_experiment_id,
            run_key=run_key,
            val_sequence=val_seq,
            paths=paths,
            config_hash=config_hash,
            initial_learning_rate=float(
                config.get("learning_rate", self.args.initial_lr)
            ),
            initial_state=resume_state,
            initial_history=history_rows,
        )

        if initial_epoch < self.args.max_epochs:
            model.fit(
                train_seq,
                validation_data=val_seq,
                initial_epoch=initial_epoch,
                epochs=self.args.max_epochs,
                callbacks=[control],
                verbose=1,
            )
        else:
            print(
                f"✓ {run_key}: max epochs already reached in resume state."
            )

        if not paths.best_weights.exists():
            raise RuntimeError(f"{run_key}: no best validation-UAR weights saved.")

        model.load_weights(paths.best_weights)

        completion = {
            "pipeline_version": PIPELINE_VERSION,
            "logical_experiment_id": logical_experiment_id,
            "run_key": run_key,
            "campaign": campaign_name,
            "seed": int(seed),
            "config_hash": config_hash,
            "training_dataset": training_dataset or SOURCE_DATASET,
            "split_sha256": effective_split_hash,
            "completed_at_utc": utc_now(),
            "completed_epochs": int(
                control.state.get("completed_epochs", initial_epoch)
            ),
            "best_epoch": control.state.get("best_epoch"),
            "best_val_uar": control.state.get("best_val_uar"),
            "stopped_early": bool(
                control.state.get("stopped_early", False)
            ),
            "best_weights": str(paths.best_weights),
        }
        atomic_write_json(paths.completion, completion)

        print(
            f"✓ {run_key}: training complete; "
            f"best val UAR={completion['best_val_uar']:.5f}"
        )

        return model, paths, completion

