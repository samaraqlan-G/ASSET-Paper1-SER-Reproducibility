def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def stable_hash(payload: dict) -> str:
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def atomic_write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.stem + ".tmp" + path.suffix)
    with tmp.open("w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)
    os.replace(tmp, path)


def atomic_write_csv(frame: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.stem + ".tmp" + path.suffix)
    frame.to_csv(tmp, index=False)
    os.replace(tmp, path)


def parse_list(text: str) -> List[str]:
    return [x.strip() for x in str(text).split(",") if x.strip()]


def parse_seeds(text: str) -> List[int]:
    vals = [int(x) for x in parse_list(text)]
    if not vals:
        raise ValueError("At least one seed is required.")
    return vals


def parse_float_list(text: str) -> List[float]:
    vals = [float(x) for x in parse_list(text)]
    if not vals:
        raise ValueError("At least one floating-point value is required.")
    return vals


@tf.keras.utils.register_keras_serializable(package="SERThesis")
class TemporalAttention(layers.Layer):
    """Lightweight trainable temporal attention pooling."""

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self.score = layers.Dense(1, use_bias=False, name="attention_score")

    def call(self, inputs):
        logits = self.score(inputs)
        weights = tf.nn.softmax(logits, axis=1)
        return tf.reduce_sum(inputs * weights, axis=1)

    def get_config(self):
        return super().get_config()


