    def stratified_bootstrap_ci(
        self,
        y_true,
        y_pred,
        seed,
        reps=None,
    ):
        """95% stratified bootstrap CIs for UAR and Macro-F1."""
        reps = int(reps or self.args.bootstrap_reps)
        rng = np.random.default_rng(int(seed) + 918273)

        y_true = np.asarray(y_true, dtype=int)
        y_pred = np.asarray(y_pred, dtype=int)

        class_indices = {
            c: np.where(y_true == c)[0]
            for c in range(NUM_CLASSES)
        }

        if any(len(v) == 0 for v in class_indices.values()):
            return {
                "uar_ci_low": np.nan,
                "uar_ci_high": np.nan,
                "macro_f1_ci_low": np.nan,
                "macro_f1_ci_high": np.nan,
                "bootstrap_reps": reps,
            }

        uars = np.empty(reps, dtype=float)
        f1s = np.empty(reps, dtype=float)

        for b in range(reps):
            sampled = np.concatenate(
                [
                    rng.choice(idx, size=len(idx), replace=True)
                    for idx in class_indices.values()
                ]
            )

            yt = y_true[sampled]
            yp = y_pred[sampled]

            uars[b] = balanced_accuracy_score(yt, yp)
            f1s[b] = f1_score(
                yt, yp, average="macro", zero_division=0
            )

        return {
            "uar_ci_low": float(np.quantile(uars, 0.025)),
            "uar_ci_high": float(np.quantile(uars, 0.975)),
            "macro_f1_ci_low": float(np.quantile(f1s, 0.025)),
            "macro_f1_ci_high": float(np.quantile(f1s, 0.975)),
            "bootstrap_reps": reps,
        }

    def analyze_final(self):
        ledger_path = self.campaign_ledger_path("final_E1_E8")
        if not ledger_path.exists():
            print("No final campaign ledger exists yet.")
            return

        df = pd.read_csv(ledger_path)

        # Per-seed generalization gaps
        internal = df.loc[
            df["evaluation_set"] == "eseravd_internal_test",
            ["experiment", "seed", "uar", "macro_f1", "accuracy"],
        ].rename(
            columns={
                "uar": "internal_uar",
                "macro_f1": "internal_macro_f1",
                "accuracy": "internal_accuracy",
            }
        )

        external = df.loc[
            df["evaluation_set"] != "eseravd_internal_test"
        ].copy()

        external = external.merge(
            internal[["experiment", "seed", "internal_uar"]],
            on=["experiment", "seed"],
            how="left",
        )

        external["uar_generalization_gap"] = (
            external["internal_uar"] - external["uar"]
        )

        external["cross_corpus_condition"] = np.where(
            external["evaluation_set"] == "maleo",
            "same_language_cross_corpus",
            "cross_language_cross_corpus",
        )

        atomic_write_csv(
            internal,
            self.summary_root / "final_internal_by_seed.csv",
        )
        atomic_write_csv(
            external,
            self.summary_root / "final_generalization_gaps_by_seed.csv",
        )

        # Publication-style aggregate
        numeric_cols = [
            "accuracy",
            "uar",
            "macro_f1",
            "mcc",
            "cohen_kappa",
        ]
        agg = (
            df.groupby(["experiment", "evaluation_set"])[numeric_cols]
            .agg(["mean", "std", "count"])
        )
        agg.columns = [
            "_".join([a, b]) for a, b in agg.columns
        ]
        agg = agg.reset_index()

        atomic_write_csv(
            agg,
            self.summary_root / "final_metrics_mean_sd.csv",
        )

        # Controlled effect sizes in UAR (per seed and evaluation set)
        pivot = df.pivot_table(
            index=["seed", "evaluation_set"],
            columns="experiment",
            values="uar",
            aggfunc="first",
        ).reset_index()

        effect_specs = {
            "ARF_contribution_E3_minus_E8": ("E3", "E8"),
            "SA_contribution_E3_minus_E4": ("E3", "E4"),
            "WA_contribution_E3_minus_E5": ("E3", "E5"),
            "WA_SA_combined_E3_minus_E6": ("E3", "E6"),
            "LS_effect_E7_minus_E3": ("E7", "E3"),
        }

        for name, (a, b) in effect_specs.items():
            if a in pivot.columns and b in pivot.columns:
                pivot[name] = pivot[a] - pivot[b]

        atomic_write_csv(
            pivot,
            self.summary_root / "final_controlled_uar_effects.csv",
        )

        # 95% stratified bootstrap confidence intervals are calculated from
        # the saved per-utterance predictions. This does not retrain models.
        bootstrap_rows = []

        for row in df.itertuples(index=False):
            run_key = f"{row.experiment}_seed{int(row.seed)}"
            pred_path = (
                self.campaign_root
                / "final_E1_E8"
                / run_key
                / "results"
                / f"{row.evaluation_set}_predictions.csv"
            )

            if not pred_path.exists():
                continue

            pred_df = pd.read_csv(pred_path)
            ci = self.stratified_bootstrap_ci(
                pred_df["true_class_index"].values,
                pred_df["pred_class_index"].values,
                seed=int(row.seed),
                reps=self.args.bootstrap_reps,
            )

            bootstrap_rows.append(
                {
                    "experiment": row.experiment,
                    "seed": int(row.seed),
                    "evaluation_set": row.evaluation_set,
                    **ci,
                }
            )

        if bootstrap_rows:
            bootstrap_df = pd.DataFrame(bootstrap_rows)
            atomic_write_csv(
                bootstrap_df,
                self.summary_root / "final_bootstrap_95ci.csv",
            )

        print("\nFINAL METRICS — MEAN / SD")
        print(agg.to_string(index=False))
        print("\nCONTROLLED UAR EFFECTS")
        print(pivot.to_string(index=False))

        if len(self.args.seeds) < 3:
            print(
                "\nNOTE: one seed is useful for engineering iteration. "
                "For publication-level mean±SD and inferential comparisons, "
                "rerun the final campaign with at least 3 independent seeds."
            )

