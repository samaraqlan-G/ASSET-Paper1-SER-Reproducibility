class SERSequence(tf.keras.utils.Sequence):
    """Deterministic, resume-aware data Sequence."""

    def __init__(
        self,
        pipeline: "SERThesisPipeline",
        dataframe: pd.DataFrame,
        batch_size: int,
        arf_mode: str,
        normalization: dict,
        training: bool = False,
        wave_aug: bool = False,
        spec_aug: bool = False,
        seed: int = 42,
        shuffle: bool = False,
        initial_epoch: int = 0,
        **kwargs,
    ):
        super().__init__(**kwargs)
        self.pipeline = pipeline
        self.df = dataframe.reset_index(drop=True).copy()
        self.batch_size = int(batch_size)
        self.arf_mode = str(arf_mode)
        self.normalization = dict(normalization)
        self.training = bool(training)
        self.wave_aug = bool(wave_aug)
        self.spec_aug = bool(spec_aug)
        self.seed = int(seed)
        self.shuffle = bool(shuffle)
        self.current_epoch = int(initial_epoch)
        self.indices = np.arange(len(self.df))
        self._prepare_epoch(self.current_epoch)

    def _prepare_epoch(self, epoch_number: int) -> None:
        self.indices = np.arange(len(self.df))
        if self.shuffle:
            rng = np.random.default_rng(self.seed + int(epoch_number))
            rng.shuffle(self.indices)

    def __len__(self):
        return int(math.ceil(len(self.df) / self.batch_size))

    def on_epoch_end(self):
        self.current_epoch += 1
        self._prepare_epoch(self.current_epoch)

    def _make_feature(self, row: pd.Series, local_seed: int) -> np.ndarray:
        rng = np.random.default_rng(local_seed)

        waveform = self.pipeline.load_mono_16k(row["canonical_path"])
        waveform = self.pipeline.pad_or_center_crop(waveform)

        # Training waveform augmentation occurs BEFORE the frozen ARF.
        if self.training and self.wave_aug:
            waveform = self.pipeline.waveform_augment(waveform, rng)

        feature = self.pipeline.waveform_to_feature(
            waveform=waveform,
            arf_mode=self.arf_mode,
        )

        feature = (
            feature - float(self.normalization["feature_mean"])
        ) / float(self.normalization["feature_std"])

        # SpecAugment occurs AFTER feature normalization.
        if self.training and self.spec_aug:
            feature = self.pipeline.spec_augment(feature, rng)

        return feature[..., np.newaxis].astype(np.float32)

    def __getitem__(self, batch_index: int):
        start = batch_index * self.batch_size
        end = min(start + self.batch_size, len(self.indices))
        batch_indices = self.indices[start:end]

        x_list, y_list = [], []

        for position, df_idx in enumerate(batch_indices):
            row = self.df.iloc[int(df_idx)]

            local_seed = (
                self.seed
                + self.current_epoch * 1_000_003
                + int(df_idx) * 101
                + position
            )

            x_list.append(self._make_feature(row, local_seed))
            y_list.append(int(row["class_index"]))

        x = np.stack(x_list, axis=0)
        y = tf.keras.utils.to_categorical(
            y_list, num_classes=NUM_CLASSES
        ).astype(np.float32)

        return x, y


class ResumableTrainingControl(tf.keras.callbacks.Callback):
    """Validation-UAR checkpointing plus two-slot interruption-safe resume."""

    def __init__(
        self,
        pipeline: "SERThesisPipeline",
        logical_experiment_id: str,
        run_key: str,
        val_sequence: SERSequence,
        paths: RunPaths,
        config_hash: str,
        initial_learning_rate: float,
        initial_state: Optional[dict] = None,
        initial_history: Optional[List[dict]] = None,
    ):
        super().__init__()
        self.pipeline = pipeline
        self.logical_experiment_id = logical_experiment_id
        self.run_key = run_key
        self.val_sequence = val_sequence
        self.paths = paths
        self.config_hash = config_hash
        self.initial_learning_rate = float(initial_learning_rate)

        self.state = (
            dict(initial_state)
            if initial_state is not None
            else {
                "pipeline_version": PIPELINE_VERSION,
                "logical_experiment_id": logical_experiment_id,
                "run_key": run_key,
                "config_hash": config_hash,
                "completed_epochs": 0,
                "best_val_uar": -1.0,
                "best_epoch": None,
                "early_stop_wait": 0,
                "lr_wait": 0,
                "current_lr": self.initial_learning_rate,
                "stopped_early": False,
                "training_complete": False,
                "active_slot": None,
            }
        )

        self.history_rows = list(initial_history or [])

    def _evaluate_validation(self) -> Tuple[float, float]:
        y_true, y_pred = [], []

        for batch_idx in range(len(self.val_sequence)):
            x_batch, y_batch = self.val_sequence[batch_idx]
            probs = self.model.predict(x_batch, verbose=0)
            y_true.extend(np.argmax(y_batch, axis=1).tolist())
            y_pred.extend(np.argmax(probs, axis=1).tolist())

        val_uar = balanced_accuracy_score(y_true, y_pred)
        val_macro_f1 = f1_score(
            y_true, y_pred, average="macro", zero_division=0
        )
        return float(val_uar), float(val_macro_f1)

    def _save_best_weights(self, epoch: int, val_uar: float) -> None:
        tmp = self.paths.best_weights.with_name("best.tmp.weights.h5")
        if tmp.exists():
            tmp.unlink()
        self.model.save_weights(tmp)
        os.replace(tmp, self.paths.best_weights)

        atomic_write_json(
            self.paths.best_state,
            {
                "pipeline_version": PIPELINE_VERSION,
                "config_hash": self.config_hash,
                "epoch": int(epoch),
                "val_uar": float(val_uar),
                "saved_at_utc": utc_now(),
            },
        )

    def _commit_resume_checkpoint(self) -> None:
        pointer = None
        if self.paths.pointer.exists():
            with self.paths.pointer.open("r", encoding="utf-8") as f:
                pointer = json.load(f)

        active = None if pointer is None else pointer.get("active_slot")
        new_slot = "B" if active == "A" else "A"

        if new_slot == "A":
            model_path = self.paths.slot_a_model
            state_path = self.paths.slot_a_state
        else:
            model_path = self.paths.slot_b_model
            state_path = self.paths.slot_b_state

        tmp_model = model_path.with_name(model_path.stem + ".tmp.keras")
        if tmp_model.exists():
            if tmp_model.is_dir():
                shutil.rmtree(tmp_model)
            else:
                tmp_model.unlink()

        self.model.save(tmp_model, overwrite=True)
        os.replace(tmp_model, model_path)

        slot_state = dict(self.state)
        slot_state["active_slot"] = new_slot
        slot_state["checkpoint_committed_at_utc"] = utc_now()
        atomic_write_json(state_path, slot_state)

        # History is allowed to be ahead of the pointer. At resume it is
        # trimmed to the committed epoch.
        atomic_write_csv(pd.DataFrame(self.history_rows), self.paths.history)

        # The pointer is written LAST. This is the transaction commit.
        atomic_write_json(
            self.paths.pointer,
            {
                "pipeline_version": PIPELINE_VERSION,
                "config_hash": self.config_hash,
                "active_slot": new_slot,
                "completed_epochs": int(self.state["completed_epochs"]),
                "committed_at_utc": utc_now(),
            },
        )

        self.state["active_slot"] = new_slot

    def on_epoch_end(self, epoch, logs=None):
        logs = dict(logs or {})
        val_uar, val_macro_f1 = self._evaluate_validation()

        logs["val_uar"] = val_uar
        logs["val_macro_f1"] = val_macro_f1

        previous_best = float(self.state.get("best_val_uar", -1.0))
        improved = val_uar > previous_best + self.pipeline.MIN_DELTA_UAR

        if improved:
            self.state["best_val_uar"] = val_uar
            self.state["best_epoch"] = int(epoch + 1)
            self.state["early_stop_wait"] = 0
            self.state["lr_wait"] = 0
            self._save_best_weights(epoch + 1, val_uar)
            print(
                f"Epoch {epoch+1}: val_uar improved to {val_uar:.5f}; "
                "best weights saved."
            )
        else:
            self.state["early_stop_wait"] = int(
                self.state.get("early_stop_wait", 0) + 1
            )
            self.state["lr_wait"] = int(self.state.get("lr_wait", 0) + 1)
            print(
                f"Epoch {epoch+1}: val_uar did not improve "
                f"from {previous_best:.5f}."
            )

        current_lr = float(
            tf.keras.backend.get_value(self.model.optimizer.learning_rate)
        )

        if (
            not improved
            and self.state["lr_wait"] >= self.pipeline.args.lr_patience
            and current_lr > self.pipeline.args.min_lr
        ):
            new_lr = max(
                current_lr * self.pipeline.args.lr_reduction_factor,
                self.pipeline.args.min_lr,
            )
            self.model.optimizer.learning_rate.assign(new_lr)
            self.state["lr_wait"] = 0
            current_lr = float(new_lr)
            print(f"Epoch {epoch+1}: learning rate reduced to {new_lr:.8g}.")

        self.state["current_lr"] = current_lr
        self.state["completed_epochs"] = int(epoch + 1)
        self.state["updated_at_utc"] = utc_now()

        should_stop = (
            self.state["early_stop_wait"]
            >= self.pipeline.args.early_stop_patience
        )
        self.state["stopped_early"] = bool(should_stop)

        row = {
            "epoch": int(epoch + 1),
            "loss": float(logs.get("loss", np.nan)),
            "accuracy": float(logs.get("accuracy", np.nan)),
            "val_loss": float(logs.get("val_loss", np.nan)),
            "val_accuracy": float(logs.get("val_accuracy", np.nan)),
            "val_uar": val_uar,
            "val_macro_f1": val_macro_f1,
            "learning_rate": current_lr,
        }

        self.history_rows = [
            r for r in self.history_rows
            if int(r["epoch"]) != int(row["epoch"])
        ]
        self.history_rows.append(row)
        self.history_rows = sorted(
            self.history_rows, key=lambda r: int(r["epoch"])
        )

        self._commit_resume_checkpoint()

        print(
            f"✓ Resume transaction committed at completed epoch {epoch+1} "
            f"(slot {self.state['active_slot']})."
        )

        if should_stop:
            self.model.stop_training = True
            print(
                f"Epoch {epoch+1}: early stopping triggered after "
                f"{self.pipeline.args.early_stop_patience} non-improving epochs."
            )


