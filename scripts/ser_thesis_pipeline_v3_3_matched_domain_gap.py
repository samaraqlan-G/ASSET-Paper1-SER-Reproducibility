    def load_mono_16k(self, path) -> np.ndarray:
        waveform, _ = librosa.load(
            str(path), sr=self.TARGET_SR, mono=True
        )
        return waveform.astype(np.float32)

    def pad_or_center_crop(self, waveform: np.ndarray) -> np.ndarray:
        n = len(waveform)

        if n == self.TARGET_SAMPLES:
            return waveform.astype(np.float32)

        if n < self.TARGET_SAMPLES:
            total_pad = self.TARGET_SAMPLES - n
            left = total_pad // 2
            right = total_pad - left
            return np.pad(
                waveform, (left, right), mode="constant"
            ).astype(np.float32)

        start = (n - self.TARGET_SAMPLES) // 2
        return waveform[
            start : start + self.TARGET_SAMPLES
        ].astype(np.float32)

    def waveform_augment(self, waveform: np.ndarray, rng) -> np.ndarray:
        if rng.random() > self.WAVE_AUG_PROB:
            return waveform.astype(np.float32)

        choice = int(rng.integers(0, 3))
        x = waveform.copy()

        if choice == 0:
            snr_db = rng.uniform(15.0, 30.0)
            signal_power = np.mean(x ** 2) + 1e-12
            noise_power = signal_power / (10.0 ** (snr_db / 10.0))
            noise = rng.normal(
                0.0, np.sqrt(noise_power), size=x.shape
            ).astype(np.float32)
            x = x + noise

        elif choice == 1:
            gain_db = rng.uniform(-6.0, 6.0)
            x = x * (10.0 ** (gain_db / 20.0))

        else:
            # Preserve v1.3 behavior for experimental comparability.
            max_shift = int(0.10 * len(x))
            shift = int(rng.integers(-max_shift, max_shift + 1))
            x = np.roll(x, shift)

        return np.clip(x, -1.0, 1.0).astype(np.float32)

    def _highpass(self, waveform: np.ndarray) -> np.ndarray:
        sos = signal.butter(
            N=4,
            Wn=70.0,
            btype="highpass",
            fs=float(self.TARGET_SR),
            output="sos",
        )
        y = signal.sosfiltfilt(sos, waveform)
        return y.astype(np.float32)

    def _preemphasis(self, waveform: np.ndarray, coef: float = 0.97) -> np.ndarray:
        x = waveform.astype(np.float32)
        if len(x) < 2:
            return x
        y = np.empty_like(x)
        y[0] = x[0]
        y[1:] = x[1:] - coef * x[:-1]
        return y.astype(np.float32)

    def _spectral_gate(self, waveform: np.ndarray) -> np.ndarray:
        """
        Controlled stationary-noise spectral subtraction candidate.

        Noise profile: median magnitude of the lowest-energy 10% STFT frames.
        Subtraction strength is fixed; no target-corpus fitting is performed.
        """
        D = librosa.stft(
            waveform,
            n_fft=self.N_FFT,
            hop_length=self.HOP_LENGTH,
            win_length=self.WIN_LENGTH,
            window="hann",
            center=False,
        )
        mag = np.abs(D)
        phase = np.exp(1j * np.angle(D))

        frame_energy = np.mean(mag ** 2, axis=0)
        n_noise = max(1, int(round(0.10 * mag.shape[1])))
        noise_idx = np.argsort(frame_energy)[:n_noise]
        noise_profile = np.median(mag[:, noise_idx], axis=1, keepdims=True)

        alpha = 1.0
        floor_ratio = 0.05
        cleaned_mag = np.maximum(
            mag - alpha * noise_profile,
            floor_ratio * mag,
        )

        cleaned = librosa.istft(
            cleaned_mag * phase,
            hop_length=self.HOP_LENGTH,
            win_length=self.WIN_LENGTH,
            window="hann",
            center=False,
            length=len(waveform),
        )
        return cleaned.astype(np.float32)

    def apply_waveform_arf(
        self, waveform: np.ndarray, arf_mode: str
    ) -> np.ndarray:
        mode = str(arf_mode).lower()

        if mode in {"none", "pcen"}:
            return waveform.astype(np.float32)
        if mode == "highpass":
            return self._highpass(waveform)
        if mode == "preemphasis":
            return self._preemphasis(waveform)
        if mode == "spectral_gate":
            return self._spectral_gate(waveform)

        raise ValueError(f"Unknown ARF mode: {arf_mode}")

    def waveform_to_feature(
        self, waveform: np.ndarray, arf_mode: str
    ) -> np.ndarray:
        mode = str(arf_mode).lower()
        x = self.apply_waveform_arf(waveform, mode)

        if mode == "pcen":
            mel = librosa.feature.melspectrogram(
                y=x,
                sr=self.TARGET_SR,
                n_fft=self.N_FFT,
                hop_length=self.HOP_LENGTH,
                win_length=self.WIN_LENGTH,
                window="hann",
                center=False,
                power=1.0,
                n_mels=self.N_MELS,
                fmin=self.FMIN,
                fmax=self.FMAX,
            )
            feat = librosa.pcen(
                mel,
                sr=self.TARGET_SR,
                hop_length=self.HOP_LENGTH,
                gain=0.98,
                bias=2.0,
                power=0.5,
                time_constant=0.4,
                eps=1e-6,
            )
            return feat.T.astype(np.float32)

        mel = librosa.feature.melspectrogram(
            y=x,
            sr=self.TARGET_SR,
            n_fft=self.N_FFT,
            hop_length=self.HOP_LENGTH,
            win_length=self.WIN_LENGTH,
            window="hann",
            center=False,
            power=2.0,
            n_mels=self.N_MELS,
            fmin=self.FMIN,
            fmax=self.FMAX,
        )

        logmel = librosa.power_to_db(
            mel, ref=1.0, top_db=self.TOP_DB
        )
        return logmel.T.astype(np.float32)

    def spec_augment(self, feature: np.ndarray, rng) -> np.ndarray:
        x = feature.copy()
        time_steps, mel_bins = x.shape

        freq_width = int(
            rng.integers(0, self.FREQ_MASK_MAX_BINS + 1)
        )
        if freq_width > 0:
            f0 = int(
                rng.integers(
                    0, max(1, mel_bins - freq_width + 1)
                )
            )
            x[:, f0 : f0 + freq_width] = 0.0

        time_max = max(
            1,
            int(round(self.TIME_MASK_MAX_FRACTION * time_steps)),
        )
        time_width = int(rng.integers(0, time_max + 1))
        if time_width > 0:
            t0 = int(
                rng.integers(
                    0, max(1, time_steps - time_width + 1)
                )
            )
            x[t0 : t0 + time_width, :] = 0.0

        return x.astype(np.float32)

