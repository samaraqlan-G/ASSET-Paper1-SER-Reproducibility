    def _load_resume(
        self, paths: RunPaths, expected_hash: str
    ) -> Tuple[Optional[tf.keras.Model], Optional[dict], List[dict]]:
        if not paths.pointer.exists():
            return None, None, []

        with paths.pointer.open("r", encoding="utf-8") as f:
            pointer = json.load(f)

        if pointer.get("config_hash") != expected_hash:
            raise RuntimeError(
                "Resume checkpoint exists but configuration hash changed. "
                "Use a new experiment root or restore the original configuration."
            )

        slot = pointer.get("active_slot")
        if slot == "A":
            model_path, state_path = (
                paths.slot_a_model,
                paths.slot_a_state,
            )
        elif slot == "B":
            model_path, state_path = (
                paths.slot_b_model,
                paths.slot_b_state,
            )
        else:
            raise RuntimeError("Invalid resume pointer slot.")

        if not model_path.exists() or not state_path.exists():
            raise RuntimeError(
                "Resume pointer exists but its committed slot is incomplete."
            )

        with state_path.open("r", encoding="utf-8") as f:
            state = json.load(f)

        if state.get("config_hash") != expected_hash:
            raise RuntimeError("Resume state configuration hash mismatch.")

        model = tf.keras.models.load_model(model_path)

        completed = int(state["completed_epochs"])
        history_rows = []
        if paths.history.exists():
            h = pd.read_csv(paths.history)
            h = h.loc[h["epoch"].astype(int) <= completed].copy()
            history_rows = h.to_dict(orient="records")

        return model, state, history_rows

