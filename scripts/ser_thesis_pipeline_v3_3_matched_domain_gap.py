    def collect_predictions(self, model, sequence):
        y_true, y_prob = [], []

        for batch_idx in range(len(sequence)):
            x_batch, y_batch = sequence[batch_idx]
            probs = model.predict(x_batch, verbose=0)
            y_true.extend(np.argmax(y_batch, axis=1).tolist())
            y_prob.extend(probs.tolist())

        y_true = np.asarray(y_true, dtype=int)
        y_prob = np.asarray(y_prob, dtype=float)
        y_pred = np.argmax(y_prob, axis=1)
        return y_true, y_pred, y_prob

    def compute_metrics(self, y_true, y_pred):
        accuracy = accuracy_score(y_true, y_pred)
        uar = balanced_accuracy_score(y_true, y_pred)
        macro_f1 = f1_score(
            y_true, y_pred, average="macro", zero_division=0
        )
        mcc = matthews_corrcoef(y_true, y_pred)
        kappa = cohen_kappa_score(y_true, y_pred)

        precision, recall, f1, support = (
            precision_recall_fscore_support(
                y_true,
                y_pred,
                labels=list(range(NUM_CLASSES)),
                zero_division=0,
            )
        )

        per_class = pd.DataFrame(
            {
                "class_index": list(range(NUM_CLASSES)),
                "label_id": list(range(1, NUM_CLASSES + 1)),
                "emotion": [
                    LABEL_ID_TO_EMOTION[i]
                    for i in range(1, NUM_CLASSES + 1)
                ],
                "precision": precision,
                "recall": recall,
                "f1": f1,
                "support": support,
            }
        )

        return {
            "accuracy": float(accuracy),
            "uar": float(uar),
            "macro_f1": float(macro_f1),
            "mcc": float(mcc),
            "cohen_kappa": float(kappa),
            "per_class": per_class,
        }

    def save_confusion_matrix(
        self, y_true, y_pred, path: Path, title: str
    ):
        cm = confusion_matrix(
            y_true,
            y_pred,
            labels=list(range(NUM_CLASSES)),
            normalize="true",
        )

        fig, ax = plt.subplots(figsize=(7, 6))
        im = ax.imshow(cm, aspect="auto")

        labels = [
            LABEL_ID_TO_EMOTION[i]
            for i in range(1, NUM_CLASSES + 1)
        ]
        ax.set_xticks(range(NUM_CLASSES))
        ax.set_yticks(range(NUM_CLASSES))
        ax.set_xticklabels(labels, rotation=45, ha="right")
        ax.set_yticklabels(labels)
        ax.set_xlabel("Predicted")
        ax.set_ylabel("True")
        ax.set_title(title)
        fig.colorbar(im, ax=ax)

        for i in range(NUM_CLASSES):
            for j in range(NUM_CLASSES):
                ax.text(
                    j, i, f"{cm[i,j]:.2f}",
                    ha="center", va="center"
                )

        fig.tight_layout()
        fig.savefig(path, dpi=300, bbox_inches="tight")
        plt.close(fig)

    def evaluate_one(
        self,
        model,
        dataframe: pd.DataFrame,
        config: dict,
        seed: int,
        logical_experiment_id: str,
        eval_name: str,
        paths: RunPaths,
        normalization_override: Optional[dict] = None,
    ):
        seq = self.make_sequence(
            dataframe=dataframe,
            config=config,
            training=False,
            seed=seed,
            shuffle=False,
            normalization_override=normalization_override,
        )

        y_true, y_pred, y_prob = self.collect_predictions(model, seq)
        metrics = self.compute_metrics(y_true, y_pred)

        metrics["per_class"].to_csv(
            paths.result_dir / f"{eval_name}_per_class_metrics.csv",
            index=False,
        )

        pred = pd.DataFrame(
            {
                "true_class_index": y_true,
                "pred_class_index": y_pred,
            }
        )
        for class_idx in range(NUM_CLASSES):
            pred[f"prob_class_{class_idx+1}"] = y_prob[:, class_idx]

        pred.to_csv(
            paths.result_dir / f"{eval_name}_predictions.csv",
            index=False,
        )

        self.save_confusion_matrix(
            y_true,
            y_pred,
            paths.figure_dir / f"{eval_name}_confusion_matrix.png",
            f"{logical_experiment_id} — {eval_name}",
        )

        return {
            "experiment": logical_experiment_id,
            "seed": int(seed),
            "evaluation_set": eval_name,
            "accuracy": metrics["accuracy"],
            "uar": metrics["uar"],
            "macro_f1": metrics["macro_f1"],
            "mcc": metrics["mcc"],
            "cohen_kappa": metrics["cohen_kappa"],
            "n_samples": int(len(dataframe)),
        }

