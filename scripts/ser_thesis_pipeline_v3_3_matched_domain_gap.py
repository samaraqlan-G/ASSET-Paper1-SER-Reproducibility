    def stage_a_arf_selection(self):
        candidates = self.args.arf_candidates

        for mode in candidates:
            if mode not in DEFAULT_ARF_CANDIDATES:
                raise ValueError(
                    f"Unsupported ARF candidate {mode!r}. "
                    f"Supported: {DEFAULT_ARF_CANDIDATES}"
                )

        experiments = {
            f"AF_{mode.upper()}": {
                "model": "cnn",
                "arf_mode": mode,
                "wave_aug": True,
                "spec_aug": True,
                "label_smoothing": 0.0,
                "role": f"ARF source-validation candidate: {mode}",
                "bottleneck": False,
                "attention": False,
            }
            for mode in candidates
        }

        completion, _ = self.run_campaign(
            "stage_A_arf_selection",
            experiments,
            evaluate_internal=False,
            evaluate_external=False,
        )

        agg = (
            completion.groupby("experiment")["best_val_uar"]
            .agg(["mean", "std", "count"])
            .reset_index()
        )
        agg["arf_mode"] = (
            agg["experiment"].str.replace("AF_", "", regex=False).str.lower()
        )
        agg = agg.sort_values(
            ["mean", "arf_mode"], ascending=[False, True]
        ).reset_index(drop=True)

        atomic_write_csv(
            agg,
            self.summary_root / "arf_selection_summary.csv",
        )

        best = agg.iloc[0]
        selected = str(best["arf_mode"])

        payload = {
            "pipeline_version": PIPELINE_VERSION,
            "selected_arf": selected,
            "selection_criterion": "highest mean best validation UAR",
            "selection_data": "E-SERAVD train/validation only",
            "target_corpora_used_for_selection": False,
            "candidate_arf_modes": candidates,
            "selected_mean_best_val_uar": float(best["mean"]),
            "seeds": self.args.seeds,
            "frozen_at_utc": utc_now(),
        }

        if self.frozen_arf_json.exists() and not self.args.refreeze_arf:
            with self.frozen_arf_json.open("r", encoding="utf-8") as f:
                old = json.load(f)
            if old.get("selected_arf") != selected:
                raise RuntimeError(
                    "An ARF is already frozen and the current selection would "
                    "change it. Use --refreeze-arf only after an explicit "
                    "methodological decision."
                )
            print(
                f"✓ Existing frozen ARF preserved: {old['selected_arf']}"
            )
        else:
            atomic_write_json(self.frozen_arf_json, payload)
            print(f"\n✓ FROZEN ARF = {selected}")

        print(agg.to_string(index=False))

