    def build_cnn(self):
        inputs = layers.Input(shape=self.INPUT_SHAPE, name="acoustic_feature")
        x = inputs

        for filters in [32, 64, 128]:
            x = layers.Conv2D(
                filters, (3, 3), padding="same", use_bias=False
            )(x)
            x = layers.BatchNormalization()(x)
            x = layers.Activation("relu")(x)
            x = layers.MaxPooling2D((2, 2))(x)
            x = layers.Dropout(0.20)(x)

        x = layers.GlobalAveragePooling2D()(x)
        x = layers.Dense(128, activation="relu")(x)
        x = layers.Dropout(0.30)(x)
        outputs = layers.Dense(
            NUM_CLASSES, activation="softmax", name="emotion"
        )(x)

        return models.Model(inputs, outputs, name="CNN")

    def build_lstm(self):
        inputs = layers.Input(shape=self.INPUT_SHAPE, name="acoustic_feature")
        x = layers.Reshape(
            (self.INPUT_TIME_STEPS, self.N_MELS)
        )(inputs)

        x = layers.LSTM(128, return_sequences=True)(x)
        x = layers.Dropout(0.25)(x)
        x = layers.LSTM(64, return_sequences=False)(x)
        x = layers.Dense(128, activation="relu")(x)
        x = layers.Dropout(0.30)(x)

        outputs = layers.Dense(
            NUM_CLASSES, activation="softmax", name="emotion"
        )(x)
        return models.Model(inputs, outputs, name="LSTM")

    def build_cnn_lstm_base(self):
        """Original v2-style CNN-LSTM retained for Stage-A/B comparison."""
        inputs = layers.Input(shape=self.INPUT_SHAPE, name="acoustic_feature")
        x = inputs

        for filters in [32, 64, 128]:
            x = layers.Conv2D(
                filters, (3, 3), padding="same", use_bias=False
            )(x)
            x = layers.BatchNormalization()(x)
            x = layers.Activation("relu")(x)
            x = layers.MaxPooling2D((1, 2))(x)
            x = layers.Dropout(0.20)(x)

        x = layers.TimeDistributed(layers.Flatten())(x)
        x = layers.LSTM(128, return_sequences=True)(x)
        x = layers.Dropout(0.25)(x)
        x = layers.LSTM(64, return_sequences=False)(x)
        x = layers.Dense(128, activation="relu")(x)
        x = layers.Dropout(0.30)(x)

        outputs = layers.Dense(
            NUM_CLASSES, activation="softmax", name="emotion"
        )(x)
        return models.Model(inputs, outputs, name="CNN_LSTM_BASE")

    def build_cnn_lstm_bottleneck(self, attention: bool = False):
        """
        Stage-B repaired CNN-LSTM.

        Temporal compression:
            448 -> 224 -> 112 -> 56 (for the current frozen input geometry)
        Frequency compression:
            128 -> 64 -> 32 -> 16
        1x1 bottleneck:
            channels 128 -> 64
        Frequency mean pooling:
            sequence becomes approximately 56 x 64 before the LSTM.
        """
        inputs = layers.Input(shape=self.INPUT_SHAPE, name="acoustic_feature")
        x = inputs

        for filters in [32, 64, 128]:
            x = layers.Conv2D(
                filters, (3, 3), padding="same", use_bias=False
            )(x)
            x = layers.BatchNormalization()(x)
            x = layers.Activation("relu")(x)
            x = layers.MaxPooling2D((2, 2))(x)
            x = layers.Dropout(0.20)(x)

        # Explicit 1x1 channel bottleneck.
        x = layers.Conv2D(
            64,
            (1, 1),
            padding="same",
            use_bias=False,
            name="bottleneck_1x1",
        )(x)
        x = layers.BatchNormalization(name="bottleneck_bn")(x)
        x = layers.Activation("relu", name="bottleneck_relu")(x)

        # Collapse frequency while preserving the compressed time axis.
        # Use built-in serializable layers rather than Lambda so that the
        # interruption-safe .keras checkpoints can always be reloaded.
        compressed_time = int(self.INPUT_TIME_STEPS // 8)
        compressed_freq = int(self.N_MELS // 8)

        x = layers.AveragePooling2D(
            pool_size=(1, compressed_freq),
            name="frequency_avg_pool",
        )(x)

        x = layers.Reshape(
            (compressed_time, 64),
            name="cnn_to_lstm_sequence",
        )(x)

        x = layers.LSTM(
            128, return_sequences=True, name="lstm_128"
        )(x)
        x = layers.Dropout(0.25)(x)

        # Attention is Stage C only.
        if attention:
            x = layers.LSTM(
                64, return_sequences=True, name="lstm_64"
            )(x)
            x = TemporalAttention(name="temporal_attention")(x)
        else:
            x = layers.LSTM(
                64, return_sequences=False, name="lstm_64"
            )(x)

        x = layers.Dense(128, activation="relu", name="dense_128")(x)
        x = layers.Dropout(0.30)(x)

        outputs = layers.Dense(
            NUM_CLASSES, activation="softmax", name="emotion"
        )(x)

        name = (
            "CNN_LSTM_BOTTLENECK_ATTENTION"
            if attention
            else "CNN_LSTM_BOTTLENECK"
        )
        return models.Model(inputs, outputs, name=name)

    def build_model(self, model_name: str):
        builders = {
            "cnn": self.build_cnn,
            "lstm": self.build_lstm,
            "cnn_lstm_base": self.build_cnn_lstm_base,
            "cnn_lstm_bottleneck": lambda: self.build_cnn_lstm_bottleneck(
                attention=False
            ),
            "cnn_lstm_attention": lambda: self.build_cnn_lstm_bottleneck(
                attention=True
            ),
        }

        if model_name not in builders:
            raise KeyError(f"Unknown model: {model_name}")

        return builders[model_name]()

    def compile_model(self, model, config: dict):
        effective_lr = float(
            config.get("learning_rate", self.args.initial_lr)
        )
        optimizer = tf.keras.optimizers.Adam(
            learning_rate=effective_lr
        )

        model.compile(
            optimizer=optimizer,
            loss=tf.keras.losses.CategoricalCrossentropy(
                label_smoothing=float(config["label_smoothing"])
            ),
            metrics=[
                tf.keras.metrics.CategoricalAccuracy(name="accuracy")
            ],
        )
        return model

