    def get_normalization(self, arf_mode: str) -> dict:
        mode = str(arf_mode).lower()

        if mode in self._norm_cache:
            return self._norm_cache[mode]

        path = self.normalization_path(mode)

        if path.exists():
            with path.open("r", encoding="utf-8") as f:
                protocol = json.load(f)

            if protocol.get("split_sha256") != self.split_hash:
                raise RuntimeError(
                    f"{mode}: normalization split hash does not match frozen split."
                )
            self._norm_cache[mode] = protocol
            return protocol

        print(
            f"\nComputing TRAINING-ONLY normalization for ARF={mode!r} ..."
        )

        feature_sum = 0.0
        feature_sumsq = 0.0
        feature_count = 0
        shape_reference = None

        for i, row in enumerate(
            self.train_df.itertuples(index=False), start=1
        ):
            waveform = self.load_mono_16k(row.canonical_path)
            waveform = self.pad_or_center_crop(waveform)
            feature = self.waveform_to_feature(waveform, mode)

            if shape_reference is None:
                shape_reference = feature.shape
            elif feature.shape != shape_reference:
                raise RuntimeError(
                    f"{mode}: feature shape mismatch "
                    f"{feature.shape} vs {shape_reference}"
                )

            f64 = feature.astype(np.float64)
            feature_sum += f64.sum()
            feature_sumsq += (f64 ** 2).sum()
            feature_count += f64.size

            if i % 250 == 0:
                print(
                    f"  ARF={mode}: {i}/{len(self.train_df)} "
                    "training files processed"
                )

        mean = float(feature_sum / feature_count)
        variance = feature_sumsq / feature_count - mean ** 2
        std = float(np.sqrt(max(variance, 1e-12)))

        protocol = {
            "pipeline_version": PIPELINE_VERSION,
            "created_at_utc": utc_now(),
            "computed_from": "E-SERAVD train only",
            "split_sha256": self.split_hash,
            "arf_mode": mode,
            "feature_mean": mean,
            "feature_std": std,
            "feature_shape": list(shape_reference),
            "target_sr": self.TARGET_SR,
            "fixed_duration_sec": self.FIXED_DURATION_SEC,
        }

        atomic_write_json(path, protocol)
        self._norm_cache[mode] = protocol

        print(
            f"✓ ARF={mode}: normalization saved. "
            f"mean={mean:.6f}, std={std:.6f}, shape={shape_reference}"
        )
        return protocol

