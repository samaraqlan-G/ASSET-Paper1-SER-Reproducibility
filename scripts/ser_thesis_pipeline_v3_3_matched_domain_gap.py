    def campaign_ledger_path(self, campaign_name: str) -> Path:
        return (
            self.campaign_root
            / campaign_name
            / "campaign_metrics.csv"
        )

    def load_ledger(self, campaign_name: str) -> pd.DataFrame:
        path = self.campaign_ledger_path(campaign_name)
        if path.exists():
            return pd.read_csv(path)
        return pd.DataFrame(
            columns=[
                "experiment",
                "seed",
                "evaluation_set",
                "accuracy",
                "uar",
                "macro_f1",
                "mcc",
                "cohen_kappa",
                "n_samples",
            ]
        )

    def upsert_metric(self, campaign_name: str, ledger, row):
        if len(ledger) > 0:
            mask = (
                (ledger["experiment"] == row["experiment"])
                & (ledger["seed"].astype(int) == int(row["seed"]))
                & (ledger["evaluation_set"] == row["evaluation_set"])
            )
            ledger = ledger.loc[~mask].copy()

        ledger = pd.concat(
            [ledger, pd.DataFrame([row])],
            ignore_index=True,
        ).sort_values(
            ["experiment", "seed", "evaluation_set"]
        ).reset_index(drop=True)

        atomic_write_csv(
            ledger,
            self.campaign_ledger_path(campaign_name),
        )
        return ledger

    def metric_exists(
        self,
        ledger: pd.DataFrame,
        experiment: str,
        seed: int,
        eval_name: str,
    ) -> bool:
        if len(ledger) == 0:
            return False
        mask = (
            (ledger["experiment"] == experiment)
            & (ledger["seed"].astype(int) == int(seed))
            & (ledger["evaluation_set"] == eval_name)
        )
        return bool(mask.any())

    def run_campaign(
        self,
        campaign_name: str,
        experiments: Dict[str, dict],
        evaluate_internal: bool = False,
        evaluate_external: bool = False,
    ):
        campaign_dir = self.campaign_root / campaign_name
        campaign_dir.mkdir(parents=True, exist_ok=True)

        matrix = pd.DataFrame(
            [{"experiment": k, **v} for k, v in experiments.items()]
        )
        atomic_write_csv(
            matrix,
            campaign_dir / "experiment_matrix.csv",
        )
        atomic_write_json(
            campaign_dir / "experiment_matrix.json",
            experiments,
        )

        if not self.args.skip_preflight:
            # One smoke test per unique model/ARF/ablation configuration.
            for exp_id, cfg in experiments.items():
                print(f"\nPreflight {campaign_name}/{exp_id}")
                self.preflight(cfg, self.args.seeds[0])

        ledger = self.load_ledger(campaign_name)

        completion_rows = []

        for exp_id, cfg in experiments.items():
            for seed in self.args.seeds:
                model, paths, completion = self.train_one(
                    campaign_name=campaign_name,
                    logical_experiment_id=exp_id,
                    config=cfg,
                    seed=seed,
                )

                completion_rows.append(
                    {
                        "experiment": exp_id,
                        "seed": seed,
                        "best_val_uar": completion["best_val_uar"],
                        "best_epoch": completion["best_epoch"],
                        "completed_epochs": completion["completed_epochs"],
                    }
                )

                plan = []
                if evaluate_internal:
                    plan.append(
                        ("eseravd_internal_test", self.internal_test_df)
                    )
                if evaluate_external:
                    plan.extend(
                        [(ds, self.external_frames[ds])
                         for ds in EXTERNAL_DATASETS]
                    )

                for eval_name, eval_df in plan:
                    if self.metric_exists(
                        ledger, exp_id, seed, eval_name
                    ):
                        print(
                            f"✓ {exp_id}/seed{seed}/{eval_name}: "
                            "already evaluated — skipping."
                        )
                        continue

                    print(
                        f"Evaluating {exp_id}/seed{seed} on {eval_name}..."
                    )
                    row = self.evaluate_one(
                        model=model,
                        dataframe=eval_df,
                        config=cfg,
                        seed=seed,
                        logical_experiment_id=exp_id,
                        eval_name=eval_name,
                        paths=paths,
                    )
                    ledger = self.upsert_metric(
                        campaign_name, ledger, row
                    )
                    print(
                        f"✓ {exp_id}/seed{seed}/{eval_name}: "
                        "metrics committed."
                    )

                del model
                tf.keras.backend.clear_session()
                gc.collect()

        completion_df = pd.DataFrame(completion_rows)
        atomic_write_csv(
            completion_df,
            campaign_dir / "validation_summary_by_run.csv",
        )

        if len(completion_df):
            agg = (
                completion_df.groupby("experiment")["best_val_uar"]
                .agg(["mean", "std", "count"])
                .reset_index()
                .sort_values("mean", ascending=False)
            )
            atomic_write_csv(
                agg,
                campaign_dir / "validation_summary_aggregate.csv",
            )
            print("\nValidation-UAR summary:")
            print(agg.to_string(index=False))

        return completion_df, ledger

